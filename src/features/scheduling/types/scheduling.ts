// ─── Frontend DTO (safe serialised shape sent to client) ─────────────────────

/**
 * CalendarEventDTO — what the frontend receives.
 * Internal fields (notesInternal, locationExact if locked) are stripped out.
 */
export interface CalendarEventDTO {
  id: string;
  type: EventType;
  title: string;
  description?: string;
  start: string;   // ISO-8601
  end: string;     // ISO-8601
  timezone: string;
  status: EventStatus;

  locationLabel?: string;          // locationGeneral always
  canViewExactLocation: boolean;
  exactLocation?: string;          // only if canViewExactLocation

  nannyId?: string;
  nannyName?: string;
  nannyCvid?: string;
  nannyUid?: string;
  agencyId?: string;
  familyId?: string;
  childId?: string;

  notesVisible?: string;
  metadata?: {
    payRate?: number;
    currency?: string;
    urgency?: UrgencyLevel;
  };
  reminderSettings?: ScheduleEvent['reminderSettings'];
  recurrence?: RecurrenceRule;
  parentEventId?: string;
  instanceIndex?: number;

  /** Which actions the current user may perform on this event. */
  allowedActions: EventAction[];
  /**
   * FullCalendar-compatible color token (frontend maps this to a hex/class).
   * 'grey' | 'yellow' | 'green' | 'red' | 'blue' | 'teal'
   */
  colorKey: CalendarColorKey;
}

export type EventAction =
  | 'accept'
  | 'decline'
  | 'confirm'
  | 'cancel'
  | 'reschedule'
  | 'complete'
  | 'view_exact_location'
  | 'edit';

export type CalendarColorKey = 'grey' | 'yellow' | 'green' | 'red' | 'blue' | 'teal';


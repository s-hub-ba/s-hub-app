// ─────────────────────────────────────────────────────────────────────────────
// Shared Scheduling Types — source of truth for all calendar-related data.
// Used by both frontend and replicated in server/services/scheduling.ts for
// the backend (which uses its own copy to avoid Vite/ESM import issues).
// ─────────────────────────────────────────────────────────────────────────────

import type { Timestamp } from 'firebase/firestore';

// ─── Enums ───────────────────────────────────────────────────────────────────

export type EventType =
  | 'availability'
  | 'blocked_time'
  | 'shift_offer'
  | 'booking_request'
  | 'booking_confirmed'
  | 'interview';

export type EventStatus =
  | 'draft'
  | 'available'
  | 'pending'
  | 'offered'
  | 'accepted'
  | 'declined'
  | 'confirmed'
  | 'cancelled'
  | 'completed';

export type UserRole = 'nanny' | 'agency' | 'family' | 'admin';

export type RecurrenceFrequency = 'daily' | 'weekly';

export type EventVisibility = 'private' | 'role_based';

export type UrgencyLevel = 'low' | 'normal' | 'high';

export type EventSource = 'agency_created' | 'family_requested' | 'nanny_availability';

// ─── Recurrence ──────────────────────────────────────────────────────────────

export interface RecurrenceRule {
  enabled: boolean;
  frequency?: RecurrenceFrequency;
  /** Interval between occurrences, e.g. every 2 weeks. Defaults to 1. */
  interval?: number;
  /** ISO day-of-week numbers (0=Sun … 6=Sat) for weekly recurrence. */
  daysOfWeek?: number[];
  /** Stop expanding after this date. */
  endsOn?: Timestamp | null;
  /** Stop expanding after this many occurrences. */
  occurrences?: number | null;
}

// ─── Core ScheduleEvent document shape (Firestore) ───────────────────────────

/**
 * ScheduleEvent — the single document type stored in `schedule_events`.
 *
 * MVP choice: recurring events are EXPANDED INTO CHILD INSTANCES on write.
 * A parent document holds the recurrence rule; each child instance stores
 * `parentEventId` so they can be managed as a group.
 * This keeps queries simple (no on-read expansion) and allows per-instance overrides.
 */
export interface ScheduleEvent {
  id: string; // Firestore doc ID – not stored in document body

  type: EventType;
  title: string;
  description?: string;

  startAt: Timestamp;
  endAt: Timestamp;
  /** IANA timezone, e.g. "America/New_York". */
  timezone: string;

  status: EventStatus;

  createdBy: string;      // userId
  createdByRole: UserRole;

  // ─── Participants ───────────────────────────────────────────────────────────
  nannyId?: string;
  agencyId?: string;
  familyId?: string;
  childId?: string;

  // ─── Location (privacy-gated) ───────────────────────────────────────────────
  /** Always visible, e.g. "Canarsie, Brooklyn". */
  locationGeneral?: string;
  /** Hidden until exactLocationUnlocked === true for the requesting user. */
  locationExact?: string;
  exactLocationUnlocked?: boolean;

  // ─── Notes ─────────────────────────────────────────────────────────────────
  notesInternal?: string; // agency/admin only
  notesVisible?: string;  // visible to all participants

  // ─── Recurrence ────────────────────────────────────────────────────────────
  recurrence?: RecurrenceRule;
  /** Set on child instances generated by a recurring parent. */
  parentEventId?: string;
  /** 0-based index of this instance within the recurrence series. */
  instanceIndex?: number;

  // ─── Visibility ────────────────────────────────────────────────────────────
  visibility: EventVisibility;

  // ─── Metadata ──────────────────────────────────────────────────────────────
  metadata?: {
    payRate?: number;
    currency?: string;
    urgency?: UrgencyLevel;
    source?: EventSource;
  };

  // ─── Reminders ─────────────────────────────────────────────────────────────
  reminderSettings?: {
    enabled: boolean;
    remind24h?: boolean;
    remind2h?: boolean;
    remind30m?: boolean;
  };

  // ─── Audit ─────────────────────────────────────────────────────────────────
  audit: {
    createdAt: Timestamp;
    updatedAt: Timestamp;
    deletedAt?: Timestamp | null;
  };
}

// ─── Availability Template ────────────────────────────────────────────────────

/**
 * Reusable weekly availability pattern for a nanny.
 * Stored in `availability_templates/{nannyId}`.
 * When applied, generates `schedule_events` of type "availability".
 */
export interface AvailabilityTemplate {
  id: string;
  nannyId: string;
  /** Day slots: key = ISO day number (0–6), value = time windows. */
  slots: Record<
    string,
    Array<{ startTime: string; endTime: string }> // "HH:mm" 24-hour
  >;
  timezone: string;
  effectiveFrom: Timestamp;
  effectiveTo?: Timestamp | null;
  audit: {
    createdAt: Timestamp;
    updatedAt: Timestamp;
  };
}

